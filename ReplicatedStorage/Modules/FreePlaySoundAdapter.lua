		return resolveSoundIdAndSpeed(p, p2, p3, p4, p5, p6)
	end,
	GetPlaybackAnchor = function()
		local character = Players.LocalPlayer.Character
		return character and character:FindFirstChild("HumanoidRootPart")
	end
}

function FreePlaySoundAdapter.PlayAction(_, p, p2, p3, p4)
	if not p then
		return
	end

	local resolved, playbackSpeed, timePosition = FreePlaySoundAdapter.Resolve(p, p2, p3, p4)

	if not resolved then
		return
	end

	local playbackAnchor = FreePlaySoundAdapter.GetPlaybackAnchor()

	if not playbackAnchor then
		return
	end

	local freePlayAction = Instance.new("Sound")
	freePlayAction.Name = "FreePlayAction"
	freePlayAction.SoundId = resolved
	freePlayAction.PlaybackSpeed = playbackSpeed

	if timePosition then
		freePlayAction.TimePosition = timePosition
	end

	freePlayAction.Volume = 1
	freePlayAction.Parent = playbackAnchor
	freePlayAction:Play()

	freePlayAction.Ended:Once(function()
		freePlayAction:Destroy()
	end)
	Debris:AddItem(freePlayAction, 8)
end

return FreePlaySoundAdapter