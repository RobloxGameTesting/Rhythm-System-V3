local v = {}

for _, item in ipairs(HighwaySkins.List) do
	v[item.Id] = item
end

function HighwaySkins.Get(p)
	return v[p] or v[HighwaySkins.DefaultId]
end

function HighwaySkins.Resolve(p, p2, p3)
	local v2 = HighwaySkins.Get(p)

	if not v2.IsRandom then
		return v2
	end

	local v3 = {}
	local v4 = {}

	for _, item in ipairs(HighwaySkins.List) do
		if item.IsRandom or item.Id == p2 then
			continue
		end

		v3[#v3 + 1] = item

		if p3 and p3[item.Id] then
			v4[#v4 + 1] = item
		end
	end

	if #v4 == 0 then
		v4 = v3
	end

	if #v4 == 0 then
		return v.Default or v2
	end

	return v4[math.random(#v4)]
end

function HighwaySkins.GetAll()
	return HighwaySkins.List
end

function HighwaySkins.IsValid(p): boolean
	return v[p] ~= nil
end

return HighwaySkins